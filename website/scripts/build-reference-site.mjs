import { readFile, writeFile, copyFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createHash } from "node:crypto";
import { buildProject } from "../../project/build-project.mjs";
import { withGeneratedOutput } from "../../project/output-transaction.mjs";
import { canonicalJson, fileLedger } from "../../assets/package-assets.mjs";
import { generateStaticDocumentation } from "../static-docs/render.mjs";
import { documentationRoutes } from "../static-docs/routes.mjs";
import { sections, release, navigationGroups } from "../site/reference-data.js";
import { generatedPages } from "../site/generated-reference-data.js";
const website = resolve(import.meta.dirname, "..");
const result = await withGeneratedOutput(resolve(website, "luastra-site"), "web", async (output) => {
  const built = await buildProject({ manifestPath: resolve(website, "app/luastra.json"), target: "web", outputDirectory: output });
  const rootHtml = resolve(output, "index.html");
  await writeFile(rootHtml, (await readFile(rootHtml, "utf8")).replace("</noscript>", '<p><a href="/docs/">Read documentation</a></p></noscript>'));
  const docs = await generateStaticDocumentation({ output, sections, pages: generatedPages, version: release.version, navigationGroups });
  const inventory = documentationRoutes({ sections, pages: generatedPages });
  const aliases = Object.fromEntries(inventory.flatMap(route => route.legacyHashes.map(hash => [hash, route.path])));
  aliases["#docs/content"] = "/docs/overview/";
  await writeFile(resolve(output, "documentation-navigation.mjs"), `export const aliases = ${JSON.stringify(aliases)};\nexport const paths = ${JSON.stringify(inventory.map(route => route.path))};\n`);
  for (const file of ["site-adapter.mjs", "site-entry.mjs", "site-navigation.css"]) await copyFile(resolve(website, "static-docs", file), resolve(output, file));
  const mainPath = resolve(output, "main.js");
  const main = await readFile(mainPath, "utf8");
  const adapterImport = 'import { DomAdapter } from "./platform/renderer/dom-adapter.mjs";';
  if (main.split(adapterImport).length !== 2) throw new Error("Website DOM adapter integration point changed");
  await writeFile(mainPath, main.replace(adapterImport, `import { DomAdapter as BaseDomAdapter } from "./platform/renderer/dom-adapter.mjs";
import { createSiteAdapter } from "./site-adapter.mjs";
import { aliases, paths } from "./documentation-navigation.mjs";
const DomAdapter = createSiteAdapter(BaseDomAdapter, { aliases, paths });`));
  const html = await readFile(rootHtml, "utf8");
  if (!html.includes('src="./main.js"')) throw new Error("Website bootstrap integration point changed");
  await writeFile(rootHtml, html.replace('src="./main.js"', 'src="./site-entry.mjs"').replace("</head>", '<link rel="stylesheet" href="./site-navigation.css" />\n</head>'));
  const exampleOutput = resolve(output, "live-example");
  await buildProject({ manifestPath: resolve(website, "app/live-example.json"), target: "web", outputDirectory: exampleOutput });
  for (const file of ["example-frame.js", "example-frame.css"]) await copyFile(resolve(website, "static-docs", file), resolve(exampleOutput, file));
  const exampleHtml = resolve(exampleOutput, "index.html");
  await writeFile(exampleHtml, (await readFile(exampleHtml, "utf8"))
    .replace("</head>", '<link rel="stylesheet" href="./example-frame.css" />\n</head>')
    .replace("</body>", '<script src="./example-frame.js"></script>\n</body>'));
  const exampleLedger = resolve(exampleOutput, "asset-manifest.json");
  const exampleManifest = JSON.parse(await readFile(exampleLedger, "utf8"));
  exampleManifest.assets = await fileLedger(exampleOutput);
  await writeFile(exampleLedger, canonicalJson(exampleManifest));
  const path = resolve(output, "asset-manifest.json");
  const manifest = JSON.parse(await readFile(path, "utf8"));
  manifest.assets = await fileLedger(output);
  const bytes = canonicalJson(manifest);
  await writeFile(path, bytes);
  return { ...built, assets: manifest.assets.length, assetManifestSha256: createHash("sha256").update(bytes).digest("hex"), staticDocuments: docs.documents };
});
console.log(JSON.stringify(result));
